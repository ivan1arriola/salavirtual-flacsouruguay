export function pertenecenAlMismoDia(inicio: Date, fin: Date, timezone: string): boolean {
  const formatter = new Intl.DateTimeFormat("en-CA", {
    timeZone: timezone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  });
  return formatter.format(inicio) === formatter.format(fin);
}
